import type { ReactNode } from "react";

/**
 * Пункт основной навигации.
 */
export interface NavItem {
  /**
   * Адрес раздела.
   */
  href: string;
  /**
   * Подпись пункта.
   */
  label: string;
}

/**
 * Пропсы шапки. Компонент презентационный и сам ничего не запрашивает.
 */
export interface NavbarProps {
  /**
   * Пункты навигации, показываются только авторизованному пользователю.
   */
  items: readonly NavItem[];
  /**
   * Текущий путь: по нему подсвечивается активный пункт.
   */
  pathname: string;
  /**
   * Куда ведёт логотип.
   */
  brandHref: string;
  /**
   * Авторизован ли пользователь: определяет, что показать справа.
   */
  isAuthenticated: boolean;
  /**
   * Дополнительные элементы справа, перед меню пользователя: переключатель темы,
   * уведомления и т.п. Navbar их не создаёт, а только размещает.
   */
  actions?: ReactNode;
  /**
   * Пока данные пользователя грузятся, справа показывается заглушка.
   */
  isLoading?: boolean;
  /**
   * Имя пользователя, из него собираются инициалы аватара.
   */
  userName?: string;
  /**
   * Почта пользователя, показывается в выпадающем меню.
   */
  userEmail?: string;
  /**
   * Обработчик выхода из аккаунта.
   */
  onLogout?: () => void;
}
